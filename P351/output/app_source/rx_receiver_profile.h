#ifndef P351_RX_RECEIVER_PROFILE_H
#define P351_RX_RECEIVER_PROFILE_H
/* P351接收默认参数，修改后重新编译PS。默认只初始化/停解调，不自动接收，
 * 不改变TX参数。UI“应用并开始”才会调谐RX2并启动PL。运行时可用UI改参数。 */
#define RX_RECEIVER_DEFAULT_LO_HZ       5137000000ULL
#define RX_RECEIVER_DEFAULT_RATE_HZ     4000000U
#define RX_RECEIVER_DEFAULT_BW_HZ       20000000U
#define RX_RECEIVER_DEFAULT_GAIN_DB     10
#define RX_RECEIVER_DEFAULT_MODE        0U /* 0 PCM/FM，1 SOQPSK-TG */
#define RX_RECEIVER_DEFAULT_LINE_CODE   0U /* PCM 0..6；SOQPSK必须0 */
#define RX_RECEIVER_DEFAULT_FRAME_BYTES 512U
#define RX_RECEIVER_DEFAULT_SYNC_WORD   0xFE6B2840ULL
#define RX_RECEIVER_DEFAULT_SYNC_BITS   32U
#define RX_RECEIVER_DEFAULT_FRAME_COUNT 1U /* >1为8位SFID的ID型复帧 */
#define RX_RECEIVER_DEFAULT_SFID_START  0U
#if RX_RECEIVER_DEFAULT_LO_HZ < 70000000ULL || RX_RECEIVER_DEFAULT_LO_HZ > 6000000000ULL
#error "RX LO default out of 70MHz..6GHz"
#endif
#if RX_RECEIVER_DEFAULT_RATE_HZ < 100000U || RX_RECEIVER_DEFAULT_RATE_HZ > 20000000U
#error "RX bitrate default out of 100k..20M"
#endif
#if RX_RECEIVER_DEFAULT_BW_HZ < RX_RECEIVER_DEFAULT_RATE_HZ || RX_RECEIVER_DEFAULT_BW_HZ > 56000000U || RX_RECEIVER_DEFAULT_BW_HZ < 200000U
#error "RX bandwidth default invalid"
#endif
#if RX_RECEIVER_DEFAULT_GAIN_DB < 0 || RX_RECEIVER_DEFAULT_GAIN_DB > 60
#error "RX gain default invalid"
#endif
#if RX_RECEIVER_DEFAULT_FRAME_BYTES < 8U || RX_RECEIVER_DEFAULT_FRAME_BYTES > 2048U || (RX_RECEIVER_DEFAULT_FRAME_BYTES & 3U)
#error "RX frame length default invalid"
#endif
#if RX_RECEIVER_DEFAULT_MODE > 1U || RX_RECEIVER_DEFAULT_LINE_CODE > 6U || (RX_RECEIVER_DEFAULT_MODE == 1U && RX_RECEIVER_DEFAULT_LINE_CODE != 0U)
#error "RX modulation/line-code default invalid"
#endif
#if RX_RECEIVER_DEFAULT_SYNC_BITS < 16U || RX_RECEIVER_DEFAULT_SYNC_BITS > 33U || (RX_RECEIVER_DEFAULT_SYNC_WORD >> RX_RECEIVER_DEFAULT_SYNC_BITS)
#error "RX sync default invalid"
#endif
#if RX_RECEIVER_DEFAULT_FRAME_COUNT < 1U || RX_RECEIVER_DEFAULT_FRAME_COUNT > 256U || RX_RECEIVER_DEFAULT_SFID_START > 1U || (RX_RECEIVER_DEFAULT_FRAME_COUNT > 1U && RX_RECEIVER_DEFAULT_FRAME_COUNT + RX_RECEIVER_DEFAULT_SFID_START > 256U) || RX_RECEIVER_DEFAULT_FRAME_BYTES * RX_RECEIVER_DEFAULT_FRAME_COUNT > 16384U
#error "RX ID major-frame default invalid"
#endif
#endif
